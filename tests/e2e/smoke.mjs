// 화면 점검: python run.py --mock 기동 → 카카오 미로딩(오프라인) 대체 경로로 좌표 입력 → 판단 실행
import { createRequire } from 'node:module';
import { spawn } from 'node:child_process';
import { readFileSync, mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const require = createRequire(import.meta.url);
let pw; try { pw = require('playwright'); } catch { pw = require('/opt/node22/lib/node_modules/playwright'); }

const PORT = 8010, ROOT = new URL('../../', import.meta.url).pathname;
const srv = spawn('python3', ['run.py', '--mock', '--port', String(PORT), '--no-browser'], { cwd: ROOT, env: { ...process.env, ACCESS_CODE: 'fire119', HELIWX_NOTAM_FILE: join(mkdtempSync(join(tmpdir(), 'hw-')), 'notams.json') } });
const fail = (m) => { console.error('FAIL:', m); srv.kill(); process.exit(1); };
for (let i = 0; i < 40; i++) { try { await fetch(`http://localhost:${PORT}/api/client-config`); break; } catch { await new Promise((r) => setTimeout(r, 200)); } }

const browser = await pw.chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: Number(process.env.DSF || 1) });
const errors = [];
page.on('console', (m) => { if (m.type() === 'error' && !/dapi\.kakao|ERR_|Failed to load resource/.test(m.text())) errors.push(m.text()); });
page.on('pageerror', (e) => errors.push(String(e)));
await page.route(/dapi\.kakao\.com/, (r) => r.abort());
await page.goto(`http://localhost:${PORT}/`);
await page.waitForSelector('#code-gate:not([hidden])', { timeout: 10000 }).catch(() => fail('접속코드 입력 창이 보이지 않음'));
await page.fill('#code-input', 'wrong'); await page.click('#code-ok');
await page.waitForFunction(() => /올바르지/.test(document.querySelector('#code-msg').textContent), null, { timeout: 5000 }).catch(() => fail('틀린 코드 안내 없음'));
await page.fill('#code-input', 'fire119'); await page.click('#code-ok');
await page.waitForSelector('#code-gate[hidden]', { state: 'attached', timeout: 5000 }).catch(() => fail('맞는 코드로 통과 못함'));
await page.waitForSelector('#map-off:not([hidden])', { timeout: 15000 }).catch(() => fail('지도 없음 안내가 보이지 않음'));
// 도·분·초 형식으로 출발지, 십진수로 목적지, 경유지 1개(도·분) 추가
await page.selectOption('#coord-fmt', 'dms');
await page.fill('#pt-from-name', '김포'); await page.fill('#pt-from-coord', `37°33'30"N 126°47'26"E`); await page.dispatchEvent('#pt-from-coord', 'change');
if (!/37\.558/.test(await page.textContent('#pt-from-msg'))) fail('도분초 해석 결과 표시 없음');
await page.fill('#pt-from-coord', '37 33'); await page.dispatchEvent('#pt-from-coord', 'change');
if (!/숫자 6개/.test(await page.textContent('#pt-from-msg'))) fail('좌표 형식 오류 안내 없음');
await page.fill('#pt-from-coord', '373330N1264726E'); await page.dispatchEvent('#pt-from-coord', 'change');
await page.click('#add-via');
await page.selectOption('#coord-fmt', 'ddm');
if (!/^37°33\.500'N/.test(await page.inputValue('#pt-from-coord'))) fail('형식 변경 시 좌표 재표시 안 됨: ' + await page.inputValue('#pt-from-coord'));
await page.fill('#pt-via1-name', '경유A'); await page.fill('#pt-via1-coord', '37 37.2, 126 52.8'); await page.dispatchEvent('#pt-via1-coord', 'change');
await page.fill('#pt-via1-stay', '10');
await page.selectOption('#coord-fmt', 'dd');
await page.fill('#pt-to-name', '서울역'); await page.fill('#pt-to-coord', '37.5547, 126.9707'); await page.dispatchEvent('#pt-to-coord', 'change');
// NOTAM 칸: 1번 저장, 2번 저장 후 삭제, 새로고침 후 유지 확인
await page.waitForSelector('#notam-1', { timeout: 5000 }).catch(() => fail('NOTAM 1번 칸 없음'));
if ((await page.locator('.nslot').count()) !== 4) fail('NOTAM 기본 4칸 아님');
if (!/공유/.test(await page.textContent('#notam-mode'))) fail('공유 저장 안내 없음');
await page.fill('#notam-1', readFileSync(ROOT + 'tests/fixtures/notam_d2840.txt', 'utf8'));
if (!/D2840\/26/.test(await page.textContent('#notam-1-title'))) fail('1번 칸 요약 없음');
await page.click('#notam-1-save');
await page.waitForFunction(() => /저장/.test(document.querySelector('#notam-1-status').textContent), null, { timeout: 5000 }).catch(() => fail('1번 저장 표시 없음'));
await page.fill('#notam-2', 'A1111/26 NOTAMN\nE)TWY A CLSD'); await page.click('#notam-2-save');
await page.waitForFunction(() => /저장/.test(document.querySelector('#notam-2-status').textContent), null, { timeout: 5000 });
page.once('dialog', (d) => d.accept()); await page.click('#notam-2-del');
await page.waitForFunction(() => document.querySelector('#notam-2').value === '', null, { timeout: 5000 }).catch(() => fail('2번 삭제 안 됨'));
await page.click('#notam-add'); if ((await page.locator('.nslot').count()) !== 5) fail('칸 추가 안 됨');
await page.click('#notam-reload');
await page.waitForFunction(() => /D2840/.test(document.querySelector('#notam-1').value) && document.querySelector('#notam-2').value === '', null, { timeout: 5000 }).catch(() => fail('새로고침 후 1번 유지/2번 삭제 상태 아님'));
await page.click('#run');
await page.waitForSelector('#overall[data-grade]', { timeout: 15000 }).catch(() => fail('종합 판정이 표시되지 않음'));
const grade = await page.getAttribute('#overall', 'data-grade');
const notamList = await page.textContent('#notam-list');
const report = await page.inputValue('#report-text');
if (!['RED', 'YELLOW', 'GREEN', 'NA'].includes(grade)) fail('등급 이상: ' + grade);
if (!notamList.includes('D2840/26')) fail('NOTAM 목록에 D2840/26 없음');
if (!report.includes('D2840/26')) fail('보고문에 D2840/26 없음');
if (!/일몰 \d\d:\d\d/.test(report)) fail('보고문에 일몰 없음');
if (!/일출/.test(await page.textContent('#sun'))) fail('일출·일몰 표시 없음');
if (!report.includes('경유A') || !report.includes('체류 10분')) fail('보고문에 경유지·체류 없음: ' + report);
if (!(await page.textContent('#rows')).includes('경유지1')) fail('근거 표에 경유지1 없음');
if ((await page.locator('#legs tr').count()) !== 2) fail('구간표 2행 아님');
if ((await page.locator('#rows tr').count()) < 6) fail('근거 표 행 부족');
if (!(await page.textContent('#landsea-auto')).includes('해상 기준')) fail('지도 없음 시 해상(엄격) 기준 안내 없음');
await page.fill('#cruise', '0'); await page.dispatchEvent('#cruise', 'change'); await page.click('#run');
await page.waitForFunction(() => document.querySelector('#run-msg').textContent.includes('판단 완료'), null, { timeout: 5000 }).catch(() => fail('순항속도 0 입력 시 멈춤'));
const hist = await page.evaluate(() => JSON.parse(localStorage.getItem('heliwx.history') || '[]'));
if (hist.length < 1 || hist[0].to !== '서울역') fail('브라우저 이력 저장 안 됨');
const [dl] = await Promise.all([page.waitForEvent('download', { timeout: 5000 }).catch(() => null), page.click('#history-csv')]);
if (!dl) fail('이력 CSV 내려받기 안 됨');
if (errors.length) fail('콘솔 오류: ' + errors.join(' / '));
if (process.env.SHOT) await page.screenshot({ path: ROOT + process.env.SHOT, fullPage: true });
console.log('PASS grade=' + grade);
await browser.close(); srv.kill();
